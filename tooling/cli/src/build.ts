// `pico-desktop build`: a portable bundle of the app for this machine's target, which runs
// without Node, pnpm, Pico or CMake:
//   dist/<name>-<version>-<target>/
//     <name>          the launcher
//     manifest.json   the app, its capabilities, the runtime it carries and every file's SHA-256
//     sbom.cdx.json   what's in it (CycloneDX)
//     THIRD-PARTY-NOTICES.txt   the frontend's dependencies' license texts
//     app/            the built frontend
//     backend/        the compiled Pico backend (release)
//     runtime/        pico-desktop-host and CEF (checked file by file first), with their licenses
import { createHash } from 'node:crypto'
import { chmodSync, cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join, relative } from 'node:path'
import { pathToFileURL } from 'node:url'
import type { ResolvedConfig } from './config'
import { generate } from './generate'
import { appArgs, shellQuote } from './host-args'
import type { Output } from './io'
import { capture } from './processes'
import {
  RuntimeError, type RuntimeManifest, currentTarget, fetchRuntime, locateRuntime, runtimeCache, unpackRuntime, verifyRuntime,
} from './runtime'
import { frontendDependencies, sbom } from './sbom'
import { notices, productionPackages } from './notices'
import { findPico } from './tools'

export interface Bundle {
  dir: string
  name: string
}

/**
 * The file-system-safe name of an app (the launcher's and the bundle's).
 *
 * @param config the app
 * @returns lowercase letters, digits and '-'
 */
export function slug(config: ResolvedConfig): string {
  return config.app.name.toLowerCase().replace(/[^a-z0-9]+/gu, '-').replace(/^-|-$/gu, '') || 'app'
}

/**
 * The launcher: the host with this app's frontend, backend, ID and capabilities.
 *
 * @param config the app
 * @returns the script
 */
export function launcher(config: ResolvedConfig): string {
  const options = appArgs(config).map(shellQuote).join(' ')

  return [
    '#!/bin/sh',
    `# Starts ${config.app.name} ${config.app.version} (generated by pico-desktop build).`,
    'here=$(dirname "$(readlink -f "$0")")',
    `exec "$here/runtime/pico-desktop-host" --app-dir="$here/app" --app-id='${config.app.id}' \\`,
    `  --backend="$here/backend/backend" ${options} "$@"`,
    '',
  ].join('\n')
}

function runtimeDir(located: string): Promise<string> {
  if (/^https?:\/\//u.test(located)) {
    return fetchRuntime(located, runtimeCache())
  }

  return located.endsWith('.tar.gz') ? unpackRuntime(located, runtimeCache()) : Promise.resolve(located)
}

async function resolvedRuntime(config: ResolvedConfig, target: string): Promise<{ dir: string, manifest: RuntimeManifest }> {
  const dir = await runtimeDir(locateRuntime(config.runtime, target))

  return { dir, manifest: verifyRuntime(dir, target) }
}

interface ViteBuild {
  build(options: Record<string, unknown>): Promise<unknown>
}

/**
 * Builds the frontend for the app's origin (relative URLs).
 *
 * @param config the app
 * @param outDir where it goes (emptied first)
 */
export async function buildFrontend(config: ResolvedConfig, outDir: string) {
  const resolved = createRequire(join(config.frontend.root, 'package.json')).resolve('vite')
  const vite = await import(pathToFileURL(resolved).href) as ViteBuild
  await vite.build({ root: config.frontend.root, base: './', logLevel: 'warn', build: { outDir, emptyOutDir: true } })
}

/**
 * The release build's arguments, with the bundle's target named. A portable backend needs the
 * architecture's baseline CPU; pico 0.4.2 compiles a host build (even with --target naming the
 * host) for this machine's CPU, so it can die with SIGILL on another machine (pico-lang #117,
 * fixed by PR #120; until a release has it, linux-x64 bundles aren't portable).
 *
 * @param entry the backend's entry file
 * @param out the executable
 * @param target the bundle's target (`linux-x64`, …)
 * @returns pico's arguments
 */
export function releaseBuildArgs(entry: string, out: string, target: string): string[] {
  return ['build', '--release', '--target', target, entry, '-o', out]
}

async function buildBackend(config: ResolvedConfig, out: string, target: string, io: Output): Promise<boolean> {
  mkdirSync(join(out, '..'), { recursive: true })
  const entry = join(config.backend.root, config.backend.entry)
  const { code, output } = await capture('pico', releaseBuildArgs(entry, out, target), config.backend.root)
  if (code !== 0) {
    output.trimEnd().split('\n').forEach(line => io.err(`pico │ ${line}`))
  }

  return code === 0
}

function hashes(dir: string, under: string): Record<string, string> {
  const walk = (path: string): string[] => readdirSync(path).flatMap(e => {
    const full = join(path, e)

    return statSync(full).isDirectory() ? walk(full) : [full]
  })

  return Object.fromEntries(walk(join(dir, under)).sort().map(f => [
    relative(dir, f), createHash('sha256').update(readFileSync(f)).digest('hex'),
  ]))
}

function writeManifest(config: ResolvedConfig, dir: string, runtime: RuntimeManifest, pico: string | null) {
  const manifest = {
    app: config.app,
    capabilities: config.capabilities,
    runtime: { version: runtime.version, target: runtime.target, cef: runtime.cef, protocol: runtime.protocol },
    pico,
    builtAt: new Date().toISOString(),
    files: { ...hashes(dir, 'app'), ...hashes(dir, 'backend') },
  }
  writeFileSync(join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
}

function supportedTarget(): string {
  const target = currentTarget()
  if (!target) {
    throw new RuntimeError(`no runtime for ${process.platform}-${process.arch} yet (linux-arm64 and linux-x64)`)
  }

  return target
}

async function picoVersion(): Promise<string | null> {
  const pico = await findPico()

  return pico ? pico.version : null
}

/**
 * Runs `step`, reporting a RuntimeError as `pico-desktop <command>: …` (exit 1).
 *
 * @param command the command's name
 * @param io where errors go
 * @param step what to run
 * @returns its exit code
 */
export async function reportingRuntimeErrors(command: string, io: Output, step: () => Promise<number>): Promise<number> {
  try {
    return await step()
  } catch (error) {
    if (!(error instanceof RuntimeError)) {
      throw error
    }
    io.err(`pico-desktop ${command}: ${error.message}`)

    return 1
  }
}

/**
 * Builds the bundle.
 *
 * @param config the app
 * @param io where output goes
 * @returns the bundle, or null if a step failed (reported)
 */
export async function buildBundle(config: ResolvedConfig, io: Output): Promise<Bundle | null> {
  const target = supportedTarget()
  const runtime = await resolvedRuntime(config, target)
  generate(config)
  const name = slug(config)
  const dir = join(config.root, 'dist', `${name}-${config.app.version}-${target}`)
  rmSync(dir, { recursive: true, force: true })
  await buildFrontend(config, join(dir, 'app'))

  if (!(await buildBackend(config, join(dir, 'backend', 'backend'), target, io))) {
    return null
  }
  cpSync(runtime.dir, join(dir, 'runtime'), { recursive: true, dereference: true })
  writeFileSync(join(dir, name), launcher(config))
  chmodSync(join(dir, name), 0o755)
  const pico = await picoVersion()
  writeManifest(config, dir, runtime.manifest, pico)
  const bom = sbom(config, runtime.manifest, pico, frontendDependencies(config.frontend.root))
  writeFileSync(join(dir, 'sbom.cdx.json'), `${JSON.stringify(bom, null, 2)}\n`)
  writeFileSync(join(dir, 'THIRD-PARTY-NOTICES.txt'), notices(name, productionPackages(config.frontend.root)))

  return { dir, name }
}

/**
 * `pico-desktop build`.
 *
 * @param config the app
 * @param io where output goes
 * @returns the exit code
 */
export function build(config: ResolvedConfig, io: Output): Promise<number> {
  return reportingRuntimeErrors('build', io, async () => {
    const bundle = await buildBundle(config, io)
    if (!bundle) {
      return 1
    }
    io.out(`built ${relative(config.root, bundle.dir)} (run it: ${relative(config.root, join(bundle.dir, bundle.name))})`)

    return 0
  })
}
