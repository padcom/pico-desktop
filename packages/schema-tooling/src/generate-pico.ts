/* eslint-disable no-template-curly-in-string -- the generator writes Pico template literals */
// Contract model → Pico: structs for maps (inline maps become named structs), Pico enums for
// text choices, payload enums for tagged unions, decoders from `Cbor` that use communicator-pico's
// payload helpers, and encoders back to `Cbor`. Pico has no async closures and throwing closures
// can't go into `map`, so the decoders are plain functions with loops.
import type { Contract, Field, Service, Type } from './ir'
import { typeName } from './generate-ts'

const UINT_BITS: Record<number, [string, string]> = {
  8: ['u8', '255'],
  16: ['u16', '65535'],
  32: ['u32', '4294967295'],
  64: ['u64', '18446744073709551615'],
}

export interface PicoOptions {
  /** What the header says the module was generated from. */
  source?: string
  /**
   * Where the runtime comes from: a package (`pico-desktop/communicator`) for apps; by default
   * the modules next to `generated/` inside communicator-pico.
   */
  runtime?: string
  /** Emit `decodeNamed` and `roundTripNamed` (the corpus tests use them; default true). */
  dispatchers?: boolean
}

const PAYLOAD_HELPERS = ['members', 'required', 'text', 'bytes', 'boolean', 'uint', 'int', 'float', 'items', 'tagOf']

const SERVICE_PARTS: Record<Service['kind'], [string, string][]> = {
  method: [['request', 'Request'], ['response', 'Response']],
  event: [['payload', 'Payload']],
  subscription: [['params', 'Params'], ['value', 'Value']],
}

const NAMEABLE = new Set<Type['kind']>(['struct', 'enum', 'union'])

const used = (body: string, names: string[]) => names.filter(h => new RegExp(`\\b${h}\\(`).test(body))

class PicoGenerator {
  private readonly out: string[] = []
  private readonly done = new Set<string>()

  private readonly source: string
  private readonly dispatchers: boolean

  constructor(private readonly contract: Contract, private readonly options: PicoOptions) {
    this.source = options.source ?? 'the ADR-0005 experiment contract'
    this.dispatchers = options.dispatchers ?? true
  }

  generate(): string {
    for (const { name, type } of this.contract.types) {
      this.named(typeName(name), type)
    }
    this.serviceTypes()

    if (this.dispatchers) {
      this.dispatcher()
    }
    const body = this.out.join('\n')
    const header = `// Generated by @pico-desktop/schema-tooling from ${this.source}: do not edit.`

    return [header, ...this.imports(body), '', body].join('\n')
  }

  private imports(body: string): string[] {
    const cbor = ['Cbor', ...used(body, ['integer'])]
    const payload = ['InvalidPayload', ...used(body, PAYLOAD_HELPERS)]
    const { runtime } = this.options

    return runtime
      ? [`import { ${[...cbor, ...payload].join(', ')} } from ${JSON.stringify(runtime)}`]
      : [`import { ${cbor.join(', ')} } from "../cbor"`, `import { ${payload.join(', ')} } from "../payload"`]
  }

  /**
   * Names the services' inline maps, choices and unions after the service and the part
   * (`math.add` → `MathAddRequest`, `MathAddResponse`; events `…Payload`; subscriptions
   * `…Params`, `…Value`), so a backend can decode and encode them. Named rules keep their names.
   */
  private serviceTypes() {
    const inline = this.contract.services.flatMap(service => SERVICE_PARTS[service.kind].map(([part, suffix]) => ({
      name: typeName(service.name) + suffix,
      type: (service as Record<string, unknown>)[part] as Type,
    })))
    inline.filter(({ type }) => NAMEABLE.has(type.kind)).forEach(({ name, type }) => this.named(name, type))
  }

  /**
   * Declares a named type (once) and its decoder.
   *
   * @param name the Pico name
   * @param type the model type
   */
  private named(name: string, type: Type) {
    if (this.done.has(name)) {
      return
    }
    this.done.add(name)
    const declare: Partial<Record<Type['kind'], () => void>> = {
      struct: () => this.struct(name, (type as { fields: Field[] }).fields),
      enum: () => this.enumeration(name, (type as { values: string[] }).values),
      union: () => this.union(name, type as { tag: string, variants: { value: string, type: Type }[] }),
    }
    const make = declare[type.kind]
    if (make) {
      make()
    } else {
      this.alias(name, type)
    }
  }

  private alias(name: string, type: Type) {
    this.out.push(`export type ${name} = ${this.picoType(type, name)}\n`)
    this.out.push(`export function decode${name}(v: Cbor, path: string): ${name} throws InvalidPayload {`)
    this.out.push(`  ${this.decodeExpr(type, 'v', 'path', name)}`)
    this.out.push('}\n')
    this.out.push(`export function encode${name}(v: ${name}): Cbor {`, `  ${this.encodeExpr(type, 'v', name)}`, '}\n')
  }

  /**
   * The Pico type for a model type; inline structs and enums become named types under `owner`.
   *
   * @param type the model type
   * @param owner the name inline types are named after
   * @returns the Pico type
   */
  private picoType(type: Type, owner: string): string {
    const simple: Partial<Record<Type['kind'], string>> = {
      int: 'i64', float: 'f64', text: 'string', bytes: 'Uint8Array', bool: 'bool',
    }
    const known = simple[type.kind]
    if (known) {
      return known
    }
    const compound: Partial<Record<Type['kind'], () => string>> = {
      uint: () => {
        const u = type as Extract<Type, { kind: 'uint' }>

        return UINT_BITS[u.max !== undefined ? 64 : u.bits ?? 64]![0]
      },
      array: () => `${this.picoType((type as { items: Type }).items, `${owner}Item`)}[]`,
      ref: () => typeName((type as { name: string }).name),
      struct: () => this.inline(owner, type),
      enum: () => this.inline(owner, type),
      union: () => this.inline(owner, type),
    }

    return compound[type.kind]!()
  }

  private inline(name: string, type: Type): string {
    this.named(name, type)

    return name
  }

  private struct(name: string, fields: Field[]) {
    // `name?: T`: an optional field a struct literal may leave out (it's null then).
    const types = fields.map(f => this.picoType(f.type, name + typeName(f.name)))
    const lines = [`export struct ${name} {`, ...fields.map((f, i) => `  ${f.name}${f.optional ? '?' : ''}: ${types[i]}`), '}\n']
    const known = `[${fields.map(f => JSON.stringify(f.name)).join(', ')}]`
    const decoder = [
      `export function decode${name}(v: Cbor, path: string): ${name} throws InvalidPayload {`,
      // A struct without fields only checks that it's an empty map.
      fields.length ? `  const m = members(v, path, ${known})` : `  members(v, path, ${known})`,
    ]
    decoder.push(...this.optionalLocals(name, fields))
    decoder.push(`  ${name} {`)

    fields.forEach((f, i) => {
      const at = `\`\${path}.${f.name}\``
      const owner = name + typeName(f.name)
      const value = f.optional ? `opt${i}` : this.decodeExpr(f.type, `required(m, ${JSON.stringify(f.name)}, path)`, at, owner)
      decoder.push(`    ${f.name}: ${value},`)
    })
    decoder.push('  }', '}\n')
    this.out.push(...lines, ...decoder, ...this.structEncoder(name, fields))
  }

  /**
   * The decoder's locals for optional fields: numbered (`opt0`), since a field's own name could
   * be `path`, `v` or `m`, which the decoder already uses.
   *
   * @param name the struct
   * @param fields its fields
   * @returns the lines
   */
  private optionalLocals(name: string, fields: Field[]): string[] {
    return fields.flatMap((f, i) => {
      if (!f.optional) {
        return []
      }
      // A typed `let` (not `if (…) null else …`, which doesn't widen a literal union to `T?`).
      const owner = name + typeName(f.name)

      return [
        `  const cbor${i} = m.get(${JSON.stringify(f.name)})`,
        `  let opt${i}: ${this.picoType(f.type, owner)}? = null`,
        `  if (cbor${i} != null) {`,
        `    opt${i} = ${this.decodeExpr(f.type, `cbor${i}`, `\`\${path}.${f.name}\``, owner)}`,
        '  }',
      ]
    })
  }

  private structEncoder(name: string, fields: Field[]): string[] {
    const param = fields.length ? 'v' : '_v'
    const lines = [`export function encode${name}(${param}: ${name}): Cbor {`, '  const m = new Map<string, Cbor>()']
    fields.forEach((f, i) => {
      const key = JSON.stringify(f.name)
      const owner = name + typeName(f.name)
      if (f.optional) {
        const local = `opt${i}`
        lines.push(
          `  const ${local} = v.${f.name}`,
          `  if (${local} != null) {`,
          `    m.set(${key}, ${this.encodeExpr(f.type, local, owner)})`,
          '  }',
        )
      } else {
        lines.push(`  m.set(${key}, ${this.encodeExpr(f.type, `v.${f.name}`, owner)})`)
      }
    })
    lines.push('  Cbor.Dict(m)', '}\n')

    return lines
  }

  private enumeration(name: string, values: string[]) {
    // A Pico enum (idiomatic, and a string-literal union isn't assignable to its optional form
    // in pico 0.4). Variants are the values in PascalCase.
    this.out.push(`export enum ${name} { ${values.map(v => typeName(v)).join(', ')} }\n`)
    this.out.push(`export function decode${name}(v: Cbor, path: string): ${name} throws InvalidPayload {`)
    this.out.push('  match (text(v, path)) {')

    for (const value of values) {
      this.out.push(`    ${JSON.stringify(value)} => ${name}.${typeName(value)},`)
    }
    this.out.push(`    _ => throw new InvalidPayload(path, ${JSON.stringify(values.join(' or '))}),`, '  }', '}\n')
    this.out.push(`export function encode${name}(v: ${name}): Cbor {`, '  match (v) {')

    for (const value of values) {
      this.out.push(`    ${typeName(value)} => Cbor.Text(${JSON.stringify(value)}),`)
    }
    this.out.push('  }', '}\n')
  }

  private union(name: string, u: { tag: string, variants: { value: string, type: Type }[] }) {
    const variant = (value: string) => typeName(value)
    const payloads = u.variants.map((v, i) => this.picoType(v.type, `${name}${i}`))
    this.out.push(`export enum ${name} {`, ...u.variants.map((v, i) => `  ${variant(v.value)}(value: ${payloads[i]}),`), '}\n')
    this.out.push(`export function decode${name}(v: Cbor, path: string): ${name} throws InvalidPayload {`)
    this.out.push(`  match (tagOf(v, path, ${JSON.stringify(u.tag)})) {`)
    u.variants.forEach((v, i) => {
      this.out.push(`    ${JSON.stringify(v.value)} => ${name}.${variant(v.value)}(decode${payloads[i]}(v, path)),`)
    })
    const expected = `${u.tag} ${u.variants.map(v => v.value).join(' or ')}`
    this.out.push(`    _ => throw new InvalidPayload(\`\${path}.${u.tag}\`, ${JSON.stringify(expected)}),`, '  }', '}\n')
    this.out.push(`export function encode${name}(v: ${name}): Cbor {`, '  match (v) {')
    u.variants.forEach((v, i) => {
      this.out.push(`    ${variant(v.value)} { value } => encode${payloads[i]}(value),`)
    })
    this.out.push('  }', '}\n')
  }

  /**
   * An expression encoding `value` (a Pico expression of the type) as `Cbor`.
   *
   * @param type the model type
   * @param value the Pico expression
   * @param owner the name inline types are named after
   * @returns the Pico expression
   */
  private encodeExpr(type: Type, value: string, owner: string): string {
    const simple: Partial<Record<Type['kind'], string>> = {
      text: 'Cbor.Text', bytes: 'Cbor.Bytes', bool: 'Cbor.Bool', float: 'Cbor.Float', int: 'integer',
    }
    const wrap = simple[type.kind]
    if (wrap) {
      return `${wrap}(${value})`
    }
    const special: Partial<Record<Type['kind'], () => string>> = {
      uint: () => `Cbor.Uint(${value} as u64)`,
      array: () => `${this.listEncoder(owner, (type as Extract<Type, { kind: 'array' }>).items)}(${value})`,
    }
    const make = special[type.kind]

    return make ? make() : `encode${this.picoType(type, owner)}(${value})`
  }

  private listEncoder(owner: string, itemType: Type): string {
    const name = `encode${owner}List`
    if (this.done.has(name)) {
      return name
    }
    this.done.add(name)
    const element = this.picoType(itemType, `${owner}Item`)
    this.out.push(
      `function ${name}(v: ${element}[]): Cbor {`,
      '  const out: Cbor[] = []',
      '  for (const e of v) {',
      `    out.push(${this.encodeExpr(itemType, 'e', `${owner}Item`)})`,
      '  }',
      '  Cbor.List(out)',
      '}\n',
    )

    return name
  }

  /**
   * An expression decoding `value` (a `Cbor` expression) at `path` (a string expression).
   *
   * @param type the model type
   * @param value the Cbor expression
   * @param path the path expression
   * @param owner the name inline types are named after
   * @returns the Pico expression
   */
  private decodeExpr(type: Type, value: string, path: string, owner: string): string {
    const simple: Partial<Record<Type['kind'], string>> = {
      int: 'int', float: 'float', text: 'text', bytes: 'bytes', bool: 'boolean',
    }
    const helper = simple[type.kind]
    const special: Partial<Record<Type['kind'], () => string>> = {
      uint: () => this.uintExpr(type as Extract<Type, { kind: 'uint' }>, value, path),
      array: () => `${this.listDecoder(owner, (type as Extract<Type, { kind: 'array' }>).items)}(${value}, ${path})`,
    }
    const make = special[type.kind]
    if (helper) {
      return `${helper}(${value}, ${path})`
    }

    return make ? make() : `decode${this.picoType(type, owner)}(${value}, ${path})`
  }

  private uintExpr(type: Extract<Type, { kind: 'uint' }>, value: string, path: string): string {
    const [pico, max] = UINT_BITS[type.bits ?? 64]!

    return `(uint(${value}, ${path}, ${type.max ?? max}) as ${type.max !== undefined ? 'u64' : pico})`
  }

  /**
   * A decoder function for arrays of `items` (declared once per owner).
   *
   * @param owner the name the function is named after
   * @param itemType the element type
   * @returns the function's name
   */
  private listDecoder(owner: string, itemType: Type): string {
    const name = `decode${owner}List`
    if (this.done.has(name)) {
      return name
    }
    this.done.add(name)
    const element = this.picoType(itemType, `${owner}Item`)
    const decodeOne = this.decodeExpr(itemType, 'e', '`${path}[${i}]`', `${owner}Item`)
    this.out.push(
      `function ${name}(v: Cbor, path: string): ${element}[] throws InvalidPayload {`,
      `  const out: ${element}[] = []`,
      '  let i = 0',
      '  for (const e of items(v, path)) {',
      `    out.push(${decodeOne})`,
      '    i += 1',
      '  }',
      '  out',
      '}\n',
    )

    return name
  }

  private dispatcher() {
    this.out.push('/// Decodes `v` as the contract type named `name` (the experiment\'s test drives it).')
    this.out.push('export function decodeNamed(name: string, v: Cbor): void throws InvalidPayload {')
    this.out.push('  switch (name) {')

    for (const { name } of this.contract.types) {
      this.out.push(`    case ${JSON.stringify(name)}:`, `      decode${typeName(name)}(v, "$")`)
    }
    this.out.push('    default:', '      throw new InvalidPayload("$", `a contract type, not ${name}`)', '  }', '}\n')
    this.out.push('/// Decodes `v` as the contract type named `name` and encodes it again (tests).')
    this.out.push('export function roundTripNamed(name: string, v: Cbor): Cbor throws InvalidPayload {')
    this.out.push('  match (name) {')

    for (const { name } of this.contract.types) {
      const t = typeName(name)
      this.out.push(`    ${JSON.stringify(name)} => encode${t}(decode${t}(v, "$")),`)
    }
    this.out.push('    _ => throw new InvalidPayload("$", `a contract type, not ${name}`),', '  }', '}\n')
  }
}

/**
 * The Pico module for a contract.
 *
 * @param contract the contract model
 * @param options the header and where the runtime comes from
 * @returns the module's source
 */
export function generatePico(contract: Contract, options: PicoOptions = {}): string {
  return new PicoGenerator(contract, options).generate()
}
